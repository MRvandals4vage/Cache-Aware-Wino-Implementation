import os
import sys
import argparse
import numpy as np
import pandas as pd
from scipy import stats as sp_stats

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT_DIR)

def bootstrap_ci(data, num_resamples=2000, alpha=0.05):
    """Compute basic bootstrap confidence interval."""
    if len(data) == 0:
        return 0.0, 0.0
    resamples = np.random.choice(data, size=(num_resamples, len(data)), replace=True)
    means = np.mean(resamples, axis=1)
    low = np.percentile(means, 100 * (alpha / 2))
    high = np.percentile(means, 100 * (1 - alpha / 2))
    return low, high

def compute_cohens_d(x, y):
    """Compute Cohen's d effect size for two independent samples."""
    nx = len(x)
    ny = len(y)
    dof = nx + ny - 2
    if dof <= 0:
        return 0.0
    pooled_std = np.sqrt(((nx - 1) * np.var(x, ddof=1) + (ny - 1) * np.var(y, ddof=1)) / dof)
    if pooled_std == 0:
        return 0.0
    return (np.mean(x) - np.mean(y)) / pooled_std

def analyze_board_results(raw_csv_path, output_dir):
    os.makedirs(output_dir, exist_ok=True)
    tables_dir = os.path.join(ROOT_DIR, "results", "tables")
    os.makedirs(tables_dir, exist_ok=True)

    if not os.path.exists(raw_csv_path):
        print(f"[analyze_all] Error: Raw CSV file {raw_csv_path} not found.")
        return

    df = pd.read_csv(raw_csv_path)
    print(f"[analyze_all] Loaded {len(df)} measurements from {raw_csv_path}")

    # Group by cell configuration
    group_cols = ["variant", "m", "T", "H", "W", "Cin", "Cout"]
    summary_rows = []

    for keys, group in df.groupby(group_cols):
        var, m, t, h, w, cin, cout = keys
        lats = group["latency_ms"].values
        gflops = group["implied_gflops"].values
        mean_lat = np.mean(lats)
        std_lat = np.std(lats, ddof=1) if len(lats) > 1 else 0.0
        ci_low, ci_high = bootstrap_ci(lats)

        summary_rows.append({
            "variant": var,
            "m": m,
            "T": t,
            "H": h,
            "W": w,
            "Cin": cin,
            "Cout": cout,
            "mean_latency_ms": mean_lat,
            "std_latency_ms": std_lat,
            "ci_95_low": ci_low,
            "ci_95_high": ci_high,
            "mean_gflops": np.mean(gflops),
            "n_reps": len(lats)
        })

    summary_df = pd.DataFrame(summary_rows)
    summary_path = os.path.join(output_dir, "summary_statistics.csv")
    summary_df.to_csv(summary_path, index=False)
    print(f"[analyze_all] Wrote statistical summary to {summary_path}")

    # Generate LaTeX Booktabs Table for Canonical Layers (H=W=56, T=1, m=2)
    canonical = summary_df[(summary_df["H"] == 56) & (summary_df["T"] == 1) & (summary_df["m"] == 2)]
    
    tex_path = os.path.join(tables_dir, "canonical_layer_latency.tex")
    with open(tex_path, "w") as f:
        f.write("% Auto-generated by scripts/analyze_all.py - DO NOT EDIT MANUALLY\n")
        f.write("\\begin{table}[htbp]\n")
        f.write("\\centering\n")
        f.write("\\caption{Benchmark Latency (ms) Across Canonical Layers ($H=W=56, T=1, m=2$)}\n")
        f.write("\\label{tab:canonical_latency}\n")
        f.write("\\begin{tabular}{lcccccc}\n")
        f.write("\\toprule\n")
        f.write("Configuration ($C_{in} \\times C_{out}$) & Direct (Naive) & Direct (NEON) & Unfused & Fused (v1) & v2 (Reg-Blk) & v4 (Packed) \\\\\n")
        f.write("\\midrule\n")

        # Pivot table for configurations
        configs = [(16, 32), (32, 16), (32, 32), (32, 64), (64, 32), (64, 64), (128, 128)]
        for cin, cout in configs:
            row_str = f"${cin} \\times {cout}$"
            for v in ["naive_direct", "neon_direct", "unfused", "fused", "v2_regblocked", "v4_pretransformed_packed"]:
                sub = canonical[(canonical["Cin"] == cin) & (canonical["Cout"] == cout) & (canonical["variant"] == v)]
                if len(sub) > 0:
                    val = sub["mean_latency_ms"].values[0]
                    row_str += f" & {val:.2f}"
                else:
                    row_str += " & --"
            row_str += " \\\\\n"
            f.write(row_str)

        f.write("\\bottomrule\n")
        f.write("\\end{tabular}\n")
        f.write("\\end{table}\n")

    print(f"[analyze_all] Wrote LaTeX table to {tex_path}")

def main():
    parser = argparse.ArgumentParser(description="CacheWinograd Master Statistical Analysis")
    parser.add_argument("--board", default="auto", help="Target board")
    parser.add_argument("--csv", default=None, help="Path to raw measurements CSV")
    args = parser.parse_args()

    board = args.board
    if board == "auto":
        board = "rpi4" if os.path.exists("results/rpi4/raw_measurements.csv") else "generic"

    csv_path = args.csv or f"results/{board}/raw_measurements.csv"
    output_dir = f"results/{board}"
    analyze_board_results(csv_path, output_dir)

if __name__ == "__main__":
    main()
